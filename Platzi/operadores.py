# Operadores aritmeticos

x = 5
y = 12

# Suma +
print("Suma", x + y)

# Resta -
print("Resta", x - y)

# Multiplicacion *
print("Mutliplicacion", x * y)

# Division / (La division siempre nos da un flotante)
print("Division", y / x)

# Modulo %
print("Modulo(resto)", y % x)

# Potencia **
print("Potencia", y ** x)  # 10 * 10 * 10 * 10 * 10

# Division Entera, no da valor decimal
print("Division Entera", y // x)

par = 8
print(par % 2 == 0)

